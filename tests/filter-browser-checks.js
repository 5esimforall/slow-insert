async (page) => {
  const checks = [];
  const check = (ok, name) => { if (!ok) throw new Error(name); checks.push(name); };
  await page.goto("http://127.0.0.1:4178/tests/fixture.html?lang=cn");
  await page.waitForFunction(() => fixtureReady);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole("button", { name: "Slow Insert — 合集搜索" }).click();
  const input = page.getByRole("combobox", { name: "搜索物品、法术或怪物" });
  const scheme = page.getByRole("combobox", { name: "速查方案" });
  const drawer = page.getByRole("region", { name: "速查筛选" });
  const rows = page.getByRole("listbox", { name: "搜索结果" }).getByRole("option");
  const box = name => page.getByRole("checkbox", { name, exact: true });
  const action = name => page.getByRole("button", { name, exact: true }).click();
  const waitRows = count => page.waitForFunction(count => document.querySelectorAll(".si-result").length === count, count);
  const reset = () => action("重置当前方案");
  await scheme.selectOption("spells");
  await waitRows(100);
  check(await drawer.isVisible(), "selecting 万法 opens its filter scheme and supports blank-query browsing");
  check(await box("环阶：零环／戏法").isChecked() && !await box("特殊：仪式").isChecked(), "ordinary checkboxes default to all, special requirements to none");
  const groupNames = await drawer.locator("summary").allTextContents();
  check(groupNames.join("/") === "特殊/凡骨/时间/环阶/学派/职业/来源", "spell groups follow 本书速查 order");

  await input.fill("fire");
  await waitRows(6);
  await action("环阶：清空");
  await waitRows(0);
  check((await page.getByRole("status").textContent()).includes("没有匹配"), "Clear means no selected values, not unlimited results");
  await box("环阶：零环／戏法").check();
  await waitRows(2);
  check((await rows.allTextContents()).every(x => x.includes("Fire Bolt")), "cantrip checkbox correctly matches level zero");
  await box("环阶：3环").check();
  await waitRows(4);
  check(true, "multiple selections in one group use OR");
  await action("来源：清空");
  await box("来源：PHB'24").check();
  await waitRows(2);
  check((await rows.allTextContents()).every(x => x.includes("PHB'24")), "different groups combine with AND and keep editions separate");
  await action("职业：清空");
  await box("职业：法师").check();
  await waitRows(2);
  check(true, "class filtering resolves exact name plus source from local reference facts");
  await reset();
  await waitRows(6);
  check(await input.inputValue() === "fire", "Reset preserves the search text");
  await box("特殊：仪式").check();
  await waitRows(1);
  check((await rows.first().textContent()).includes("Fire Ward"), "positive special requirements filter spells");
  await box("凡骨：无专注").check();
  await waitRows(0);
  check(true, "special and mundane requirements must all be satisfied");
  await reset();

  await input.fill("bulk");
  await waitRows(100);
  await box("特殊：仪式").check();
  await waitRows(1);
  check((await rows.first().textContent()).includes("Bulk late ritual"), "filtering occurs before the 100-result limit");
  await input.fill("");
  await waitRows(3);
  await box("特殊：有价值／会消耗的材料").check();
  await waitRows(1);
  check((await rows.first().textContent()).includes("Gem Spell"), "costly-material metadata works with ritual requirements");
  await box("凡骨：无价值／不消耗的材料").check();
  await waitRows(0);
  check(true, "contradictory material requirements correctly yield zero matches");
  await reset();
  await action("职业：清空");
  await box("职业：法师").check();
  await waitRows(4);
  check(!(await rows.allTextContents()).some(x => x.includes("Bulk")), "same-source but different names are not guessed into class lists");

  await scheme.selectOption("magic");
  await waitRows(2);
  check((await rows.allTextContents()).every(x => /Test Wand|Test Potion/.test(x)), "万器 excludes mundane weapons and spells");
  check((await drawer.locator("summary").allTextContents()).join("/") === "稀有度/类别/同调/来源", "magic-item groups follow 本书速查");
  await action("稀有度：清空");
  await box("稀有度：珍稀").check();
  await waitRows(1);
  await action("类别：清空");
  await box("类别：魔杖").check();
  await action("同调：清空");
  await box("同调：是").check();
  await waitRows(1);
  check((await rows.first().textContent()).includes("Test Wand"), "rarity, category and attunement combine");
  await rows.first().dragTo(page.locator("#drop"));
  check(await page.evaluate(() => fixtureState.drop?.type === "Item" && fixtureState.drop.uuid === "Item.wand"), "magic items still use native Item drag payloads");

  await scheme.selectOption("monsters");
  await waitRows(5);
  check(!(await rows.allTextContents()).some(x => x.includes("Player character")), "万兽 includes only NPC Actors, not player characters");
  check((await drawer.locator("summary").allTextContents()).join("/") === "挑战等级/传奇动作/生物体型/生物类型/来源", "monster groups follow 本书速查");
  const min = page.getByRole("combobox", { name: "挑战等级最小值" });
  const max = page.getByRole("combobox", { name: "挑战等级最大值" });
  await min.selectOption("0.125");
  await max.selectOption("0.5");
  await waitRows(1);
  check((await rows.first().textContent()).includes("Scout"), "fractional CR bounds compare numerically");
  await min.selectOption("0");
  await waitRows(2);
  check((await rows.allTextContents()).some(x => x.includes("Rat")), "CR zero is a valid boundary");
  await action("重置挑战等级筛选");
  await min.selectOption("10");
  await max.selectOption("2");
  await waitRows(1);
  check(await min.inputValue() === "2" && await max.inputValue() === "10", "reversed CR endpoints are normalized in the UI");
  check((await rows.first().textContent()).includes("Fire Elemental"), "CR range is inclusive and excludes unknown values");
  await reset();
  await action("传奇动作：清空");
  await box("传奇动作：有").check();
  await action("生物体型：清空");
  await box("生物体型：超巨型").check();
  await action("生物类型：清空");
  await box("生物类型：龙类").check();
  await waitRows(1);
  check((await rows.first().textContent()).includes("Dragon"), "legendary action, size and creature type filters combine");
  await rows.first().dragTo(page.locator("#drop"));
  check(await page.evaluate(() => fixtureState.drop?.type === "Actor" && fixtureState.drop.uuid === "Actor.dragon"), "monster drag uses Actor, not Item");
  await rows.first().click();
  check(await page.evaluate(() => fixtureState.opened.at(-1) === "Dragon"), "clicking a monster opens its Actor document");
  check(await box("来源：MM'25").isVisible() && await box("来源：PHB'24").count() === 0, "source options are specific to the selected scheme");

  await scheme.selectOption("magic");
  await waitRows(1);
  check((await rows.first().textContent()).includes("Test Wand"), "magic-item selections survive switching schemes");
  await scheme.selectOption("spells");
  await waitRows(4);
  check(await box("职业：法师").isChecked() && !await box("职业：牧师").isChecked(), "spell selections are independent of other schemes");
  const saved = await page.evaluate(() => game.settings.get("slow-insert", "filters"));
  await page.addInitScript(seed => { globalThis.fixtureSettingsSeed = { "slow-insert.filters": seed }; }, saved);
  await page.reload();
  await page.waitForFunction(() => fixtureReady);
  await page.getByRole("button", { name: "Slow Insert — 合集搜索" }).click();
  await waitRows(4);
  check(await scheme.inputValue() === "spells", "scheme and profiles restore on fresh module initialization");
  await page.getByRole("button", { name: /^显示筛选/ }).click();
  await reset();
  const finder = page.getByRole("searchbox", { name: "查找来源筛选" });
  await finder.fill("phb");
  check(await box("来源：PHB'14").isVisible() && !await box("来源：TCoE").isVisible(), "source finder only narrows the options list");
  await finder.fill("");
  check(await page.evaluate(() => !window.pwned && !document.querySelector(".si-filter-choice img")), "source names remain inert text");
  await input.press("Escape");
  check(!await drawer.isVisible() && await input.isVisible(), "Escape collapses filters before the panel");
  await page.getByRole("button", { name: /^显示筛选/ }).press("Escape");
  check(!await input.isVisible(), "second Escape closes the panel");
  await page.getByRole("button", { name: "Slow Insert — 合集搜索" }).click();
  await scheme.selectOption("monsters");
  await waitRows(1);
  await page.evaluate(() => {
    const dragon = fixtureItems.find(item => item.uuid === "Actor.dragon");
    dragon.system.resources.legact.max = 0;
    Hooks.callAll("updateActor", dragon);
  });
  await waitRows(0);
  check(true, "Actor updates invalidate cached filter metadata");
  await reset();
  await waitRows(5);
  await page.setViewportSize({ width: 390, height: 600 });
  await page.waitForFunction(() => {
    const bounds = document.querySelector("#slow-insert-panel").getBoundingClientRect();
    return bounds.left >= 0 && bounds.right <= innerWidth;
  });
  check(await page.evaluate(() => {
    const panel = document.querySelector("#slow-insert-panel");
    return panel.scrollWidth <= panel.clientWidth && document.querySelector(".si-results").getBoundingClientRect().height >= 56;
  }), "checkbox schemes fit narrow panels and retain usable results");
  check(await page.evaluate(() => CONFIG.Actor.compendiumIndexFields.includes("system.details.cr")), "NPC metadata fields register before indexing");
  return { passed: checks.length, checks };
}
