/** Build the first, deliberately bounded grouping registry from the read-only audit. */
import fs from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
import { reviewedSpellGroups } from "./reviewed-spell-groups.mjs";
const directory=path.resolve(process.argv[2] ?? "output/dedup-audit-2026-11-01");
const findings=JSON.parse(await fs.readFile(path.join(directory,"findings.json")));
const records=JSON.parse(await fs.readFile(path.join(directory,"records.json")));
const packs=JSON.parse(await fs.readFile(path.join(directory,"packs.json")));
const scope=JSON.parse(await fs.readFile(path.join(directory,"scope.json")));
const approvals=JSON.parse(await fs.readFile(new URL("./grouping-approvals.json",import.meta.url)));
const index=new Map(records.map(r=>[r.uuid,r])), packIndex=new Map(packs.map(p=>[p.id,p]));
const members={}, groups={};
const tags=r=>[...(r.flags.some(f=>["midi-qol","dae","chris-premades","gambits-premades","autoanimations"].includes(f))?["automation"]:[]),
  ...(r.flags.includes("native-class-growth")?["dependency"]:[])];
function add(key,kind,rows,risk=null) {
  groups[key]={kind,rules:rows[0].rules,members:rows.map(r=>r.uuid),...(risk?{risk}:{})};
  // Runtime Babele can translate a copied dependency using the original pack's
  // aliases. Accept only aliases evidenced inside this same audited family.
  const names=[...new Set(rows.flatMap(r=>[r.name,...r.aliases]))];
  for(const r of rows) {
    const pack=packIndex.get(r.pack);
    if(!Object.hasOwn(r.stats,"modifiedTime"))throw new Error("Re-run audit to collect modification stamps");
    members[r.uuid]={group:key,type:r.type,rules:r.rules,identifier:r.identifier,level:r.basics.level??null,school:r.basics.school??null,
      modifiedTime:r.stats.modifiedTime,package:pack.package,packageVersion:pack.packageVersion??null,
      names:[r.name,...names.filter(name=>name!==r.name)],tags:tags(r)};
  }
}
for(const uuids of findings.exactAllowlist) {
  const rows=uuids.map(uuid=>index.get(uuid));
  const key="exact:"+createHash("sha256").update(uuids.slice().sort().join("\n")).digest("hex").slice(0,20);
  add(key,"exact",rows);
}
for(const group of findings.spellCandidates) {
  const rows=group.members.map(r=>index.get(r.uuid));
  // A larger spell family takes precedence over an identical sub-pair.
  add(`spell:${rows[0].rules}:${rows[0].identifier}`,"spell",rows);
}
for(const approval of reviewedSpellGroups(findings,records,approvals.groups)) {
  const approved=new Set(approval.rows.map(r=>r.uuid));
  const existingKeys=new Set([approval.key,...approval.rows.map(r=>members[r.uuid]?.group).filter(Boolean)]);
  for(const key of existingKeys)if(groups[key]?.members.some(uuid=>!approved.has(uuid))) {
    throw new Error(`Spell family gained unreviewed members: ${key}`);
  }
  add(approval.key,"spell",approval.rows,approval.risk);
}
for(const [key,group] of Object.entries(groups)) {
  group.members=group.members.filter(uuid=>members[uuid]?.group===key);
  if(group.members.length<2)delete groups[key];
}
const review={};
for(const r of findings.editionConflicts)review[r.uuid]="edition";
for(const group of findings.spellProblems)for(const r of group.members)review[r.uuid]="spell";
const registry={schema:1,auditDate:scope.generatedAt.slice(0,10),scope:"Locally audited compendium records; never world documents",groups,members,review};
await fs.writeFile("module/data/grouping-registry.mjs",`// Generated by tools/build-grouping-registry.mjs. Metadata only, no rule text.\nexport const GROUPING_REGISTRY = ${JSON.stringify(registry)};\n`);
console.log(JSON.stringify({groups:Object.keys(groups).length,members:Object.keys(members).length,review:Object.keys(review).length,exactAuditPairs:findings.exactAllowlist.length}));
