"""Extract names and classification facts only; never copy rules/descriptions or source JS.

Usage: python3 tools/extract-quick-reference.py /path/to/5echm-web
"""
from html.parser import HTMLParser
from pathlib import Path
import hashlib
import json
import re
import sys

root = Path(sys.argv[1]).expanduser()
out = Path(__file__).resolve().parents[1] / 'module' / 'data'
classes = dict(zip(['吟游诗人', '牧师', '德鲁伊', '圣武士', '游侠', '术士', '法师', '魔契师', '奇械师', '无职'],
                   ['bard', 'cleric', 'druid', 'paladin', 'ranger', 'sorcerer', 'wizard', 'warlock', 'artificer', 'none']))
categories = dict(zip(['护甲', '药水', '戒指', '权杖', '卷轴', '法杖', '魔杖', '武器', '奇物'],
                      ['armor', 'potion', 'ring', 'rod', 'scroll', 'staff', 'wand', 'weapon', 'wondrous']))
rarities = dict(zip(['普通', '非普', '珍稀', '极珍', '传说', '神器', '多种'],
                    ['common', 'uncommon', 'rare', 'veryRare', 'legendary', 'artifact', 'varies']))
attunement = {'是': 'yes', '否': 'no', '特殊': 'special'}

class Page(HTMLParser):
    def __init__(self):
        super().__init__()
        self.books = set()
        self.rows = []
    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'input' and attrs.get('name') == 'book':
            self.books.add(attrs['value'])
        if tag == 'tr' and attrs.get('tags'):
            self.rows.append(attrs)

files = [('spell', '速查/法术速查/5E万法大全.html'), ('spell', '速查/法术速查/合作方万法大全.html'),
         ('magic', '速查/5E万器大全.htm'), ('magic', '速查/合作万器大全.htm')]
records, sources = [], []
for kind, relative in files:
    path = root / 'topics' / relative
    raw = path.read_bytes()
    page = Page()
    page.feed(raw.decode('utf-8'))
    count = 0
    for row in page.rows:
        name = row.get('spell' if kind == 'spell' else 'item', '').strip()
        tags = row['tags'].split()
        books = [tag for tag in tags if tag in page.books]
        if not name or len(books) != 1:
            continue  # No speculative source matching.
        names = [name]
        latin = re.search('[A-Za-z]', name)
        if latin and latin.start() > 0:
            names += [name[:latin.start()].strip(), name[latin.start():].strip()]
        record = {'kind': kind, 'book': books[0], 'names': list(dict.fromkeys(names))}
        if kind == 'spell':
            record['classes'] = [classes[tag] for tag in tags if tag in classes]
        else:
            record['category'] = next((categories[tag] for tag in tags if tag in categories), None)
            record['rarity'] = next((rarities[tag] for tag in tags if tag in rarities), None)
            record['attunement'] = next((attunement[tag] for tag in tags if tag in attunement), None)
        records.append(record)
        count += 1
    sources.append({'file': f'topics/{relative}', 'sha256': hashlib.sha256(raw).hexdigest(), 'rows': len(page.rows), 'extracted': count})
out.mkdir(parents=True, exist_ok=True)
(out / 'quick-reference.mjs').write_text('// Generated by tools/extract-quick-reference.py. Classification facts only.\nexport const QUICK_REFERENCE = ' + json.dumps(records, ensure_ascii=False, separators=(',', ':')) + ';\n')
(out / 'provenance.json').write_text(json.dumps({'reference': '5e不全书 · 本书速查', 'sources': sources,
    'fields': ['name aliases', 'source abbreviation', 'spell class lists', 'magic item category/rarity/attunement'],
    'matching': 'Exact normalized name and source; conflicting classifications are unknown. No descriptions or rules text.'}, ensure_ascii=False, indent=2) + '\n')
print(json.dumps({'records': len(records), 'sources': sources}, ensure_ascii=False, indent=2))
